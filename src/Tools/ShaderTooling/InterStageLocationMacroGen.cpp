/// InterStageLocationMacroGen — interstage_locations.glsl 生成器
///
/// 唯一输入：ShaderSemanticRegistry（inc/hgl/mtl/ShaderSemanticRegistry.h 的结构 +
/// src/ShaderProgramBuild/contract/ShaderSemanticRegistry.cpp 的规范表）。
/// 宏名取 InterStageSemanticInfo::location_macro，数值取 ::stable_location。
///
/// 用法：
///   InterStageLocationMacroGen --emit            输出完整 interstage_locations.glsl（CRLF）
///   InterStageLocationMacroGen --verify <path>   生成内容与指定文件比对（忽略行尾差异）
///
/// ShaderLibrary/contract/interstage_locations.glsl 是生成物，禁止手改；
/// location 变更入口在 ShaderSemanticRegistry.cpp 的规范表，改后运行本工具重新生成。
/// --verify 已接入构建期（interstage_locations_verify ALL）与 ctest。

#include <hgl/mtl/ShaderSemanticRegistry.h>

#include <cstdio>
#include <cstring>
#include <string>
#include <io.h>
#include <fcntl.h>

namespace
{
    using hgl::graph::mtl::GetInterStageSemanticInfo;
    using hgl::graph::mtl::GetInterStageSemanticInfoCount;
    using hgl::graph::mtl::InterStageSemantic;
    using hgl::graph::mtl::InterStageSemanticInfo;

    constexpr const char *FILE_PREAMBLE =
        "// GENERATED by InterStageLocationMacroGen — DO NOT EDIT\n"
        "// 宏名/数值真源：src/ShaderProgramBuild/contract/ShaderSemanticRegistry.cpp\n"
        "//   （InterStageSemanticRegistry[] 的 location_macro / stable_location）\n"
        "// 重新生成：InterStageLocationMacroGen --emit > ShaderLibrary/contract/interstage_locations.glsl\n"
        "//\n"
        "// 双 Stage（Mesh Shader ↔ Fragment Shader）交接语义位置的 GLSL 侧定义。\n"
        "// 规则：严禁在 .mesh / .frag 中硬编码数字 location，一律使用本文件定义的宏。\n"
        "\n"
        "#ifndef HGL_INTERSTAGE_LOCATIONS_GLSL\n"
        "#define HGL_INTERSTAGE_LOCATIONS_GLSL\n"
        "\n";

    constexpr const char *FILE_EPILOGUE =
        "\n#endif // HGL_INTERSTAGE_LOCATIONS_GLSL\n";

    /// 按 stable_location 升序输出：注册表顺序是语义枚举顺序（StyleID 排在最后
    /// 但 location 是 4），生成物按 location 排比较好核对。
    uint32_t BuildLocationOrder(uint32_t *out_index, const uint32_t max_count)
    {
        const uint32_t count = GetInterStageSemanticInfoCount();
        uint32_t valid = 0;

        for (uint32_t index = 1; index < count && valid < max_count; ++index)
        {
            const InterStageSemanticInfo *info =
                GetInterStageSemanticInfo(static_cast<InterStageSemantic>(index));
            if (info && info->location_macro && info->location_macro[0])
                out_index[valid++] = index;
        }

        for (uint32_t i = 1; i < valid; ++i)
        {
            const uint32_t key_index = out_index[i];
            const InterStageSemanticInfo *key = GetInterStageSemanticInfo(
                static_cast<InterStageSemantic>(key_index));
            uint32_t j = i;
            while (j > 0)
            {
                const InterStageSemanticInfo *prev = GetInterStageSemanticInfo(
                    static_cast<InterStageSemantic>(out_index[j - 1]));
                if (prev->stable_location <= key->stable_location)
                    break;
                out_index[j] = out_index[j - 1];
                --j;
            }
            out_index[j] = key_index;
        }

        return valid;
    }

    std::string GenerateGLSL()
    {
        uint32_t order[64];
        const uint32_t count = BuildLocationOrder(order, 64);

        size_t name_width = 0;
        for (uint32_t i = 0; i < count; ++i)
        {
            const InterStageSemanticInfo *info = GetInterStageSemanticInfo(
                static_cast<InterStageSemantic>(order[i]));
            const size_t length = std::strlen(info->location_macro);
            if (length > name_width)
                name_width = length;
        }

        std::string out(FILE_PREAMBLE);
        for (uint32_t i = 0; i < count; ++i)
        {
            const InterStageSemanticInfo *info = GetInterStageSemanticInfo(
                static_cast<InterStageSemantic>(order[i]));

            out += "#define ";
            out += info->location_macro;

            // 数值列对齐到最长宏名之后两格，读起来是张表。
            size_t padding = name_width - std::strlen(info->location_macro) + 2;
            while (padding-- > 0)
                out += ' ';

            out += std::to_string(info->stable_location);
            out += '\n';
        }

        out += FILE_EPILOGUE;
        return out;
    }

    std::string ToCRLF(const std::string &src)
    {
        std::string out;
        out.reserve(src.size() + src.size() / 8);

        for (const char c : src)
        {
            if (c == '\n')
                out += "\r\n";
            else
                out += c;
        }

        return out;
    }

    // 忽略行尾差异（\r\n 与 \n 等价），使校验不受 git 检出行尾策略影响。
    std::string NormalizeEOL(const std::string &src)
    {
        std::string out;
        out.reserve(src.size());

        for (const char c : src)
            if (c != '\r')
                out += c;

        return out;
    }

    bool ReadTextFile(const char *filename, std::string &out)
    {
        FILE *fp = std::fopen(filename, "rb");
        if (!fp)
            return false;

        char buf[4096];
        size_t n;
        while ((n = std::fread(buf, 1, sizeof(buf), fp)) > 0)
            out.append(buf, n);

        std::fclose(fp);
        return true;
    }

    int Verify(const char *filename)
    {
        std::string disk;
        if (!ReadTextFile(filename, disk))
        {
            std::fprintf(stderr,
                "[InterStageLocationMacroGen] cannot read file: %s\n", filename);
            return 2;
        }

        const std::string generated = NormalizeEOL(GenerateGLSL());
        const std::string on_disk = NormalizeEOL(disk);

        if (generated == on_disk)
        {
            std::printf(
                "[InterStageLocationMacroGen] verify OK: %s\n", filename);
            return 0;
        }

        size_t line = 1, pos = 0;
        while (pos < generated.size() && pos < on_disk.size()
            && generated[pos] == on_disk[pos])
        {
            if (generated[pos] == '\n')
                ++line;
            ++pos;
        }

        std::fprintf(stderr,
            "[InterStageLocationMacroGen] MISMATCH: %s line %zu\n"
            "  generated: %.96s\n"
            "  on disk  : %.96s\n"
            "\n"
            "interstage_locations.glsl 是生成物，禁止手改。\n"
            "如需变更：修改 ShaderSemanticRegistry.cpp 的 InterStageSemanticRegistry\n"
            "（location_macro / stable_location），再运行\n"
            "  InterStageLocationMacroGen --emit > ShaderLibrary/contract/interstage_locations.glsl\n",
            filename, line,
            generated.c_str() + pos,
            on_disk.c_str() + pos);
        return 1;
    }
}//namespace

int main(int argc, char **argv)
{
    if (argc >= 2 && std::strcmp(argv[1], "--emit") == 0)
    {
        // 文本模式会把 "\r\n" 再翻译成 "\r\r\n"，必须切二进制输出
        _setmode(_fileno(stdout), _O_BINARY);

        const std::string crlf = ToCRLF(GenerateGLSL());
        std::fwrite(crlf.data(), 1, crlf.size(), stdout);
        return 0;
    }

    if (argc >= 3 && std::strcmp(argv[1], "--verify") == 0)
        return Verify(argv[2]);

    std::fprintf(stderr,
        "usage:\n"
        "  InterStageLocationMacroGen --emit            输出 interstage_locations.glsl 到 stdout\n"
        "  InterStageLocationMacroGen --verify <path>   校验文件与注册表一致\n");
    return 3;
}
