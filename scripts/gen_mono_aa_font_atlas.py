# ============================================================================
#  光栅化：胶囊体笔画 + ss x ss 超采样覆盖率
# ============================================================================

def _segments(strokes):
    segs = []
    for st in strokes:
        for i in range(len(st) - 1):
            x1, y1 = st[i]
            x2, y2 = st[i + 1]
            segs.append((x1, y1, x2, y2))
    return segs


def render_glyph_aa(strokes, cell_w, cell_h, ss, half_w, kx, ky, y0):
    """把一个字形渲染成 cell_w x cell_h 的 8-bit 覆盖率块。

    kx/ky : 设计单位 -> 像素的比例
    y0    : 设计坐标 y 对应的像素行偏移基准（py = y0 - y*ky）
    """
    out = bytearray(cell_w * cell_h)
    segs = _segments(strokes)
    if not segs:
        return out

    h2 = half_w * half_w
    inv = 1.0 / ss
    total = ss * ss

    # 预先算好子采样在像素内的偏移
    offs = [((sx + 0.5) * inv, (sy + 0.5) * inv)
            for sy in range(ss) for sx in range(ss)]

    for j in range(cell_h):
        row_base = j * cell_w
        for i in range(cell_w):
            cnt = 0
            for (ox, oy) in offs:
                X = (i + ox) / kx
                Y = (y0 - (j + oy)) / ky
                hit = False
                for (x1, y1, x2, y2) in segs:
                    dx = x2 - x1
                    dy = y2 - y1
                    l2 = dx * dx + dy * dy
                    if l2 <= 1e-12:
                        px = X - x1
                        py = Y - y1
                    else:
                        t = ((X - x1) * dx + (Y - y1) * dy) / l2
                        if t < 0.0:
                            t = 0.0
                        elif t > 1.0:
                            t = 1.0
                        px = X - (x1 + t * dx)
                        py = Y - (y1 + t * dy)
                    if px * px + py * py <= h2:
                        hit = True
                        break
                if hit:
                    cnt += 1
            if cnt:
                out[row_base + i] = (cnt * 255 + total // 2) // total
    return out


# ============================================================================
#  1-bit 点阵导入（可选，需版权干净的字库）
# ============================================================================

def render_glyph_1bit(data, g, row_bytes, cell_w, cell_h):
    out = bytearray(cell_w * cell_h)
    base = g * row_bytes * cell_h
    for r in range(cell_h):
        for x in range(cell_w):
            byte = data[base + r * row_bytes + (x // 8)]
            if (byte >> (7 - (x & 7))) & 1:      # MSB-first
                out[r * cell_w + x] = 255
    return out


# ============================================================================
#  图集拼装 / PNG 输出
# ============================================================================

def grid_cols(n):
    cols = 1
    while cols * cols < n:
        cols <<= 1
    return cols


def compose(cells, cell_w, cell_h, padding, glyph_count):
    cols = grid_cols(glyph_count)
    rows = (glyph_count + cols - 1) // cols
    stride_w = cell_w + padding
    stride_h = cell_h + padding
    aw = cols * stride_w
    ah = rows * stride_h
    pixels = bytearray(aw * ah)          # 全黑，padding 区天然为 0

    for g in range(glyph_count):
        blk = cells[g]
        if blk is None:
            continue
        ox = (g % cols) * stride_w
        oy = (g // cols) * stride_h
        for r in range(cell_h):
            src = r * cell_w
            dst = (oy + r) * aw + ox
            pixels[dst:dst + cell_w] = blk[src:src + cell_w]

    return pixels, aw, ah, cols, rows, stride_w, stride_h


def _chunk(tag, payload):
    return (struct.pack(">I", len(payload)) + tag + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))


def write_png(path, pixels, width, height):
    stride = width
    raw = bytearray()
    for y in range(height):
        raw.append(0)                    # filter = None
        raw += pixels[y * stride:(y + 1) * stride]

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0)  # 8bit 灰度
    png = (b"\x89PNG\r\n\x1a\n"
           + _chunk(b"IHDR", ihdr)
           + _chunk(b"IDAT", zlib.compress(bytes(raw), 9))
           + _chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(png)


