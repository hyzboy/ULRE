"""
gen_mono_aa_font_atlas.py — 生成 8x16 单色(R8)灰度字库图集，带抗锯齿。

⚠️ 版权说明
  早期版本直接把 IBM PC VGA 的 8x16 ROM 点阵(如 VGA8.F16)转成图集。那套字形
  属于 IBM BIOS ROM 数据，商用有风险。本脚本因此**不再使用任何第三方字库数据**：
  内置一套从零手绘的原创矢量笔画字体（见 GLYPHS），只覆盖 ASCII 0x20..0x7E，
  与 IBM VGA 字形无关，可自由使用。

抗锯齿
  既然图集本来就是 8-bit 灰度，笔画按「胶囊体(有圆头的线段)」在 cell 内做
  ss x ss 超采样覆盖率计算，得到 64 级(ss=8)灰度边缘，天然抗锯齿，无需 mipmap。

图集布局（与引擎 MonoBitmapFontSource 一致）
  - cell = cell_w x cell_h 像素，字形画在左上角。
  - 每个 cell 步长 (cell_w+padding) x (cell_h+padding)，右侧/下侧留 padding 像素
    全黑空白，避免 linear 过滤把邻字像素混进来。
  - 网格 cols x rows（cols 取 2 的幂，>= sqrt(glyph_count)）。
  - 输出单通道 8-bit 灰度 PNG（R 通道 = 覆盖率），可直接喂给 TexConv。

用法
  # 默认：内置原创字体，8x16，抗锯齿
  python gen_mono_aa_font_atlas.py -o res/font/Mono8x16.png

  # 参数
  --cell-w 8 --cell-h 16    cell 尺寸（矢量字按设计空间 8x16 等比伸缩，
                            放大整倍就传 --cell-w 16 --cell-h 32）
  --ss 8                    每像素超采样数 ss x ss（8 -> 64 级灰度）
  --stroke 1.2              笔画粗细（设计单位，1 = 1 像素）
  --padding 2               每字右/下留白像素
  --glyphs 256              图集字符数（默认 256，多余格子留黑）

  # 可选：导入版权干净的外部 1-bit 点阵字库(每行字节数=ceil(w/8)，MSB-first)
  python gen_mono_aa_font_atlas.py --f16 myfont.f16 -o out.png

仅依赖 Python 标准库（math + zlib + struct）。
"""

