#  主流程
# ============================================================================

def main(argv):
    ap = argparse.ArgumentParser(
        description="生成 8x16 单色灰度过抗锯齿字库图集（内置原创矢量字体）")
    ap.add_argument("--f16", help="可选：导入外部 1-bit 点阵字库(需版权干净)")
    ap.add_argument("-o", "--output", default="mono8x16.png", help="输出 PNG")
    ap.add_argument("--cell-w", type=int, default=8, help="cell 宽（默认 8）")
    ap.add_argument("--cell-h", type=int, default=16, help="cell 高（默认 16）")
    ap.add_argument("--glyphs", type=int, default=256, help="图集字符数（默认 256）")
    ap.add_argument("--ss", type=int, default=8,
                    help="每像素超采样 ss x ss（默认 8 -> 64 级灰度）")
    ap.add_argument("--stroke", type=float, default=1.2,
                    help="笔画粗细（设计单位，默认 1.2 像素）")
    ap.add_argument("--padding", type=int, default=2,
                    help="每字右/下留白像素（默认 2，规避 linear 过滤串色）")
    args = ap.parse_args(argv)

    if args.padding < 0:
        ap.error("--padding 不能为负")
    if args.ss < 1:
        ap.error("--ss 必须 >= 1")

    cw, ch = args.cell_w, args.cell_h
    cells = [None] * args.glyphs

    if args.f16:
        with open(args.f16, "rb") as f:
            data = f.read()
        row_bytes = (cw + 7) // 8
        need = row_bytes * ch * args.glyphs
        if len(data) < need:
            ap.error(f"文件只有 {len(data)} 字节，至少需要 {need}")
        for g in range(args.glyphs):
            cells[g] = render_glyph_1bit(data, g, row_bytes, cw, ch)
        src_desc = f"1-bit {args.f16}"
    else:
        # 设计空间 8x16 -> cell 等比伸缩（改 cell 尺寸即可放大整倍，如 16x32）
        kx = cw / DESIGN_W
        ky = ch / (DESIGN_TOP - DESIGN_BOTTOM)
        y0 = DESIGN_TOP * ky
        for g in range(args.glyphs):
            if g > 0x7E:
                break
            strokes = GLYPHS.get(chr(g), [])
            cells[g] = render_glyph_aa(strokes, cw, ch, args.ss,
                                       args.stroke * 0.5, kx, ky, y0)
        src_desc = "built-in original vector font (ASCII 0x20-0x7E)"

    pixels, w, h, cols, rows, sw, sh = compose(
        cells, cw, ch, args.padding, args.glyphs)
    write_png(args.output, pixels, w, h)

    print(f"OK -> {args.output}")
    print(f"  source : {src_desc}")
    print(f"  grid   : {cols} x {rows}, atlas {w} x {h} px")
    print(f"  cell   : {cw} x {ch}, padding {args.padding} "
          f"(stride {sw} x {sh})")
    if not args.f16:
        print(f"  raster : ss={args.ss} ({args.ss * args.ss} levels), "
              f"stroke={args.stroke}")


if __name__ == "__main__":
    main(sys.argv[1:])
