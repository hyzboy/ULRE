def _bq(p0, c, p1, n=10):
    """二次贝塞尔采样 -> 点列。"""
    out = []
    for i in range(n + 1):
        t = i / n
        u = 1.0 - t
        out.append((u * u * p0[0] + 2 * u * t * c[0] + t * t * p1[0],
                    u * u * p0[1] + 2 * u * t * c[1] + t * t * p1[1]))
    return out


def _ell(cx, cy, rx, ry, a0, a1, step=12.0):
    """椭圆弧采样（角度制，a0 -> a1）。"""
    n = max(6, int(abs(a1 - a0) / step) + 1)
    out = []
    for i in range(n + 1):
        a = math.radians(a0 + (a1 - a0) * i / n)
        out.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))
    return out


def _cat(*segs):
    """把若干点列/单点首尾相接，去掉接头重复点。"""
    pts = []
    for s in segs:
        s = [s] if isinstance(s, tuple) else list(s)
        if pts and s:
            a, b = pts[-1], s[0]
            if abs(a[0] - b[0]) < 1e-9 and abs(a[1] - b[1]) < 1e-9:
                s = s[1:]
        pts.extend(s)
    return pts


